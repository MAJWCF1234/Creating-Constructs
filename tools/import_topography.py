"""Import curated 32×32 topography textures for rock/dirt/moss/gravel.

Upsamples with Lanczos to 128×128 (smooth — avoids voxel stair-steps).
Writes src/topo_textures.inc and patches Creating Constructs.html TOPO maps.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = Path(r"O:\Assets\Textures\8_topography")
OUT_INC = ROOT / "src" / "topo_textures.inc"
OUT_DIR = ROOT / "assets" / "nature" / "topo"
HTML = ROOT / "Creating Constructs.html"

PICKS = [
    ("rock_sandstone", "1_stone/mossy_faded_orange_sandstone_2a06a.png"),
    ("rock_sandstone_top", "1_stone/mossy_faded_orange_sandstone_top_35w73.png"),
    ("rock_limestone", "1_stone/light_limestone_boulders_pufrc.png"),
    ("rock_limestone_mossy", "1_stone/mossy_light_limestone_boulders_194qi.png"),
    ("rock_granite", "1_stone/dark_gray_granite_d9p2d.png"),
    ("rock_brown_sandstone", "1_stone/brown_sandstone_6q5oe.png"),
    ("rock_schist_mossy", "1_stone/mossy_blue_schist_0y61i.png"),
    ("dirt_earth", "5_dirt/brown_earth_118xl.png"),
    ("dirt_rocky", "5_dirt/rocky_soil_mkrqh.png"),
    ("dirt_mossy", "5_dirt/mossy_soil_m41dz.png"),
    ("moss_thick", "4_grass_leaves/thick_moss_rdb9p.png"),
    ("gravel_gray", "6_debris_gravel/gray_gravel_0jd6n.png"),
    ("gravel_stones", "6_debris_gravel/small_stones_0yoa9.png"),
    ("gravel_mossy", "6_debris_gravel/mossy_sandstone_debris_1dib6.png"),
]


def load128(rel: str) -> Image.Image:
    path = SRC / rel
    if not path.exists():
        raise SystemExit(f"missing texture: {path}")
    im = Image.open(path).convert("RGBA")
    return im.resize((128, 128), Image.Resampling.LANCZOS)


def c_array(name: str, im: Image.Image) -> str:
    data = ",".join(str(b) for b in im.tobytes())
    return f"const unsigned char topo_{name}_rgba[128*128*4]={{{data}}};"


def js_texture(name: str, im128: Image.Image) -> str:
    """Embed smooth 128×128 topo with linear filtering."""
    arr = ",".join(str(b) for b in im128.tobytes())
    return (
        f"const TOPO_{name.upper()}=(function(){{"
        f"const c=document.createElement('canvas');c.width=c.height=128;"
        f"const g=c.getContext('2d'),sid=g.createImageData(128,128);sid.data.set([{arr}]);g.putImageData(sid,0,0);"
        f"const t=new THREE.CanvasTexture(c);t.magFilter=THREE.LinearFilter;t.minFilter=THREE.LinearMipmapLinearFilter;"
        f"t.generateMipmaps=true;t.wrapS=t.wrapT=THREE.RepeatWrapping;t.repeat.set(1.35,1.35);t.needsUpdate=true;return t}})();"
    )


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    images: list[tuple[str, Image.Image, str]] = []
    for name, rel in PICKS:
        im = load128(rel)
        images.append((name, im, rel))
        im.save(OUT_DIR / f"{name}.png")
        print(f"  {name} <- {rel}")

    lines = [
        "// Auto-generated by tools/import_topography.py — 32→128 Lanczos topography (smooth).",
        f"constexpr int TopoTextureCount={len(images)};",
    ]
    for name, im, _ in images:
        lines.append(c_array(name, im))
    lines.append(
        "const unsigned char* topoPixels[TopoTextureCount]={"
        + ",".join(f"topo_{name}_rgba" for name, _, _ in images)
        + "};"
    )
    idx = {name: i for i, (name, _, _) in enumerate(images)}
    for key, const in [
        ("rock_sandstone", "TopoRockSandstone"),
        ("rock_sandstone_top", "TopoRockSandstoneTop"),
        ("rock_limestone", "TopoRockLimestone"),
        ("rock_limestone_mossy", "TopoRockLimestoneMossy"),
        ("rock_granite", "TopoRockGranite"),
        ("rock_brown_sandstone", "TopoRockBrown"),
        ("rock_schist_mossy", "TopoRockSchist"),
        ("dirt_earth", "TopoDirt"),
        ("dirt_rocky", "TopoDirtRocky"),
        ("dirt_mossy", "TopoDirtMossy"),
        ("moss_thick", "TopoMoss"),
        ("gravel_gray", "TopoGravel"),
        ("gravel_stones", "TopoStones"),
        ("gravel_mossy", "TopoGravelMossy"),
    ]:
        lines.append(f"constexpr int {const}={idx[key]};")
    lines.append("// Runtime: topoLayer(i) = 9 + NatureTextureCount + i  (boardform is 8+NatureTextureCount)")
    OUT_INC.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT_INC} ({OUT_INC.stat().st_size} bytes)")

    s = HTML.read_text(encoding="utf-8")
    js_parts = [js_texture(name, im) for name, im, _ in images]
    rock_js = (
        "\n".join(js_parts)
        + "\n"
        + "rockM=new THREE.MeshStandardMaterial({map:TOPO_ROCK_BROWN_SANDSTONE,bumpMap:TOPO_ROCK_BROWN_SANDSTONE,"
        "bumpScale:1.85,color:0xf0e6d8,roughness:.92,flatShading:false}),"
        "dirtM=new THREE.MeshStandardMaterial({map:TOPO_DIRT_EARTH,bumpMap:TOPO_DIRT_EARTH,"
        "bumpScale:2.0,color:0xffffff,roughness:.98,flatShading:true}),"
        "topoMossM=new THREE.MeshStandardMaterial({map:TOPO_MOSS_THICK,bumpMap:TOPO_MOSS_THICK,"
        "bumpScale:2.4,color:0xffffff,roughness:1,flatShading:true}),"
        "topoGravelM=new THREE.MeshStandardMaterial({map:TOPO_GRAVEL_GRAY,bumpMap:TOPO_GRAVEL_GRAY,"
        "bumpScale:2.2,color:0xffffff,roughness:.95,flatShading:true}),"
        "waterM=new THREE.MeshStandardMaterial({color:0x3a6a72,roughness:.12,metalness:.08,transparent:true,opacity:.78,depthWrite:false});"
    )
    mat = r"new THREE\.MeshStandardMaterial\(\{[^}]+\}\)"
    pat = re.compile(
        r"const TOPO_ROCK_SANDSTONE=\(function\(\)\{.*?\}\)\(\);\s*"
        r"(?:const TOPO_[A-Z0-9_]+=\(function\(\)\{.*?\}\)\(\);\s*)*"
        rf"rockM={mat},"
        rf"dirtM={mat},"
        rf"(?:topoMossM={mat},)?"
        rf"(?:topoGravelM={mat},)?"
        rf"waterM={mat};",
        re.S,
    )
    if not pat.search(s):
        raise SystemExit("HTML TOPO + rockM block not found")
    s = pat.sub(rock_js, s, count=1)
    print("patched HTML TOPO textures + rockM block")

    s = s.replace(
        "if(type===17)addBox(g,w,.36,d,cx,-.30,cz,moss);",
        "if(type===17)addBox(g,w,.36,d,cx,-.30,cz,typeof topoMossM!=='undefined'?topoMossM:moss);",
        1,
    )
    s = s.replace(
        "rng.next()<.55?rockM:dirtM",
        "rng.next()<.4?rockM:rng.next()<.5?topoGravelM:dirtM",
        1,
    )

    tmp = HTML.with_name("Creating Constructs.html.topo_import_tmp")
    tmp.write_text(s, encoding="utf-8")
    tmp.replace(HTML)
    (OUT_DIR / "manifest.json").write_text(
        json.dumps([{"name": n, "source": r} for n, _, r in images], indent=2),
        encoding="utf-8",
    )
    print("done")


if __name__ == "__main__":
    main()

"""Pack src/generated/prop_models.inc + prop_textures.inc into Creating Constructs.html.

Writes the block between /*PROP_PACK*/ and /*PROP_PACK_END*/ (inserted before `const meshes=`):
texture pack, prop materials, mesh decoder and the defs entries for pieces 104-127.
Rerun after tools/prepare_props.py.
"""
from __future__ import annotations
import re, struct, base64, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = (ROOT / "src/generated/prop_models.inc").read_text(encoding="utf-8")
TEX = (ROOT / "src/generated/prop_textures.inc").read_text(encoding="utf-8")
MANIFEST = json.loads((ROOT / "assets/props/manifest.json").read_text(encoding="utf-8"))
HTML = ROOT / "Creating Constructs.html"
START, END = "/*PROP_PACK*/", "/*PROP_PACK_END*/"
BASE = int(re.search(r"PropMaterialBase=(\d+)", TEX).group(1))


def rgba(name: str) -> bytes:
    m = re.search(rf"const unsigned char prop_{name}_rgba\[\] = \{{([^}}]+)\}}", TEX)
    nums = [int(x) for x in m.group(1).split(",") if x.strip()]
    assert len(nums) == 128 * 128 * 4, name
    return bytes(nums)


def mesh(name: str) -> str:
    start = MODELS.find(f"const NatureVertex prop_{name}[]")
    assert start >= 0, name
    end = MODELS.find("const NatureVertex ", start + 10)
    body = MODELS[start:end if end > 0 else len(MODELS)]
    verts = re.findall(r"\{\{([-\d.eE+]+)f?,([-\d.eE+]+)f?,([-\d.eE+]+)f?\},\{([-\d.eE+]+)f?,([-\d.eE+]+)f?,([-\d.eE+]+)f?\},([-\d.eE+]+)f?,([-\d.eE+]+)f?,(\d+)\}", body)
    buf, mats = bytearray(), bytearray()
    for v in verts:
        buf += struct.pack("<8f", *[float(x) for x in v[:8]])
        mats.append(int(v[8]) & 255)
    return base64.b64encode(struct.pack("<I", len(verts)) + bytes(buf) + bytes(mats)).decode("ascii")


textures = MANIFEST["textures"]
tex_pack = [base64.b64encode(rgba(t["name"])).decode("ascii") for t in textures]
tiling = [t["tiling"] if t["tileable"] else 0 for t in textures]

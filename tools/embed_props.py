lines.append(END)
block = "\r\n".join(lines) + "\r\n"

html = HTML.read_bytes().decode("utf-8")
if START in html:
    a, b = html.index(START), html.index(END) + len(END)
    while html[b:b + 2] == "\r\n":
        b += 2
    html = html[:a] + block + html[b:]
else:
    anchor = "const meshes=defs.map("
    assert html.count(anchor) == 1
    html = html.replace(anchor, block + anchor)
HTML.write_bytes(html.encode("utf-8"))
print(f"embedded {len(mesh_pack)} meshes, {len(tex_pack)} textures, pieces 104-127")

         "const propMats=PROP_TEX_PACK.map((b64,i)=>{const t=texFromRGBA(b64);const tile=PROP_TILING[i];if(tile){t.flipY=true;t.repeat.set(tile,tile);t.needsUpdate=true;}const metal=i>=4&&i<=6;return new THREE.MeshStandardMaterial({map:t,alphaTest:.5,roughness:metal?.5:.9,metalness:metal?.5:0})});",
